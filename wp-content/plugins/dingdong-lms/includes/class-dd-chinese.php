	 * 문자열을 간체자로 변환한다. 비문자열/빈 문자열은 그대로 반환.
	 */
	public static function to_simplified( $text ) {
		if ( ! is_string( $text ) || $text === '' ) {
			return $text;
		}
		if ( self::$map === null ) {
			self::build_map();
		}
		// 코드포인트 단위로 분해 후 매핑 (CJK는 1글자 = 1코드포인트).
		$chars = preg_split( '//u', $text, -1, PREG_SPLIT_NO_EMPTY );
		if ( ! is_array( $chars ) ) {
			return $text; // preg_split 실패(비UTF-8 등) 시 원본 유지.
		}
		$out = '';
		foreach ( $chars as $c ) {
			$out .= isset( self::$map[ $c ] ) ? self::$map[ $c ] : $c;
		}
		return $out;
	}

	/**
	 * 문자열에 번체 전용 글자가 하나라도 있으면 true.
	 */
	public static function has_traditional( $text ) {
		if ( ! is_string( $text ) || $text === '' ) {
			return false;
		}
		if ( self::$map === null ) {
			self::build_map();
		}
		$chars = preg_split( '//u', $text, -1, PREG_SPLIT_NO_EMPTY );
		if ( ! is_array( $chars ) ) {
			return false;
		}
		foreach ( $chars as $c ) {
			if ( isset( self::$map[ $c ] ) ) {
				return true;
			}
		}
		return false;
	}

	/**
	 * 문자열/배열을 재귀적으로 간체 변환한다. 배열 키는 보존(값만 변환).
	 * Gemini 결과(슬라이드/퀴즈/대화 등 중첩 구조) 보정용 안전망.
	 */
	public static function convert_deep( $data ) {
		if ( is_string( $data ) ) {
			return self::to_simplified( $data );
		}
		if ( is_array( $data ) ) {
			$out = array();
			foreach ( $data as $k => $v ) {
				$out[ $k ] = self::convert_deep( $v );
			}
			return $out;
		}
		return $data; // int/bool/null 등은 그대로.
	}

